"""
Global explainability reports — which features drive the forecasts overall.

    python -m app.ml.explain_report          (also run by python -m app.ml.train)

Writes to reports/:
    feature_importance.png     mean |contribution| per feature, Ridge vs LightGBM, side by side
    shap_summary_lightgbm.png  SHAP summary ("beeswarm") for the tree model
    explainability.md          the numbers behind both plots

Global vs local
---------------
Local  = why THIS forecast (the /explain endpoint, app/ml/explain.py).
Global = which features matter across ALL forecasts: the average size of
each feature's contribution, mean(|contribution|), on the log1p scale.
Both use the same exact contributions, so the global picture is literally
the average of the local ones.

Why not LightGBM's built-in "split"/"gain" importance alone?
------------------------------------------------------------
Split counts and gain describe how the TREES were built, not how much a
feature moves predictions; they are known to favour high-cardinality
features. Mean |SHAP| measures effect on the actual output, and it is
comparable between the two models. Gain is still reported for reference.
"""
import logging

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import shap

from app.config.settings import resolve_path, settings
from app.ml.explain import contributions
from app.ml.features import FEATURES, TARGET, build_features, load_daily_sales
from app.ml.forecasting.models import make_lightgbm

logger = logging.getLogger(__name__)

SHAP_SAMPLE_ROWS = 2_000      # rows drawn for the beeswarm plot (all rows feed the importance table)
RANDOM_STATE = 42


def mean_abs_contributions(model, X: pd.DataFrame) -> pd.Series:
    return contributions(model, X).values.abs().mean().sort_values(ascending=False)


def build_reports(deployed_model, daily: pd.DataFrame, reports) -> list:
    """deployed_model = the selected, fitted forecaster (Ridge today). Returns files written."""
    reports.mkdir(parents=True, exist_ok=True)
    features = build_features(daily)
    X, y = features[FEATURES], features[TARGET]

    # The tree model is refit on the same data the deployed model saw, for a fair comparison
    lightgbm = make_lightgbm().fit(X, y)

    importance = pd.DataFrame({
        "Ridge (deployed)": mean_abs_contributions(deployed_model, X),
        "LightGBM": mean_abs_contributions(lightgbm, X),
    }).sort_values("Ridge (deployed)", ascending=False)
    gain = pd.Series(lightgbm.regressor_.booster_.feature_importance("gain"), index=FEATURES)
    importance["LightGBM gain share"] = (gain / gain.sum()).reindex(importance.index)

    # ---- 1. Side-by-side importance -----------------------------------------
    fig, ax = plt.subplots(figsize=(9, 5.5))
    order = importance.index[::-1]
    positions = np.arange(len(order))
    ax.barh(positions + 0.2, importance.loc[order, "Ridge (deployed)"], height=0.4, label="Ridge (deployed)", color="tab:blue")
    ax.barh(positions - 0.2, importance.loc[order, "LightGBM"], height=0.4, label="LightGBM", color="tab:orange")
    ax.set_yticks(positions, order)
    ax.set_xlabel("Mean |contribution| to log(1 + forecast)")
    ax.set_title("Global feature importance (exact contributions, all rows)", loc="left", fontsize=11)
    ax.legend(loc="lower right")
    ax.grid(axis="x", alpha=0.3)
    fig.tight_layout()
    importance_png = reports / "feature_importance.png"
    fig.savefig(importance_png, dpi=110)
    plt.close(fig)

    # ---- 2. SHAP summary for the tree model --------------------------------
    sample = X.sample(min(SHAP_SAMPLE_ROWS, len(X)), random_state=RANDOM_STATE)
    shap_values = shap.TreeExplainer(lightgbm.regressor_).shap_values(sample)
    plot_frame = sample.assign(product_id=sample["product_id"].cat.codes)    # beeswarm colours need numbers
    shap.summary_plot(shap_values, plot_frame, show=False, max_display=len(FEATURES))
    plt.title("LightGBM - SHAP summary (log1p scale)", loc="left", fontsize=11)
    plt.tight_layout()
    shap_png = reports / "shap_summary_lightgbm.png"
    plt.savefig(shap_png, dpi=110)
    plt.close("all")

    # ---- 3. Table ----------------------------------------------------------
    table = reports / "explainability.md"
    table.write_text(_markdown(importance, len(X), len(sample)), encoding="utf-8")
    return [importance_png, shap_png, table]


def _markdown(importance: pd.DataFrame, rows: int, sample_rows: int) -> str:
    ridge_top = importance["Ridge (deployed)"].nlargest(3).index.tolist()
    lgbm_top = importance["LightGBM"].nlargest(3).index.tolist()
    lines = [
        "# Explainability",
        "",
        "Generated by `python -m app.ml.explain_report`. Global importance = mean |contribution| of each feature "
        f"to log(1 + forecast), over all {rows:,} rows. Ridge contributions are exact (coefficient x value); "
        "LightGBM contributions are TreeSHAP values.",
        "",
        "| Feature | Ridge (deployed) | LightGBM | LightGBM gain share |",
        "|---|---:|---:|---:|",
    ]
    for feature, row in importance.iterrows():
        lines.append(f"| `{feature}` | {row['Ridge (deployed)']:.3f} | {row['LightGBM']:.3f} | {row['LightGBM gain share']:.1%} |")
    lines += [
        "",
        f"- Ridge's top 3: {', '.join(f'`{f}`' for f in ridge_top)}",
        f"- LightGBM's top 3: {', '.join(f'`{f}`' for f in lgbm_top)}",
        "",
        "Reading it: a contribution c multiplies (1 + forecast) by exp(c). A mean |contribution| of 0.40 means the "
        "feature typically moves the forecast by a factor of about 1.5 up or down.",
        "",
        "![Feature importance](feature_importance.png)",
        "",
        f"![SHAP summary](shap_summary_lightgbm.png) - each dot is one product-day ({sample_rows:,} sampled); "
        "position = effect on the forecast, colour = the feature's value (red high, blue low).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    from app.config.logging import setup_logging
    from app.ml.model_store import load_bundle
    setup_logging()

    daily = load_daily_sales(resolve_path(settings.processed_data_dir) / "daily_sales.csv")
    files = build_reports(load_bundle().model, daily, resolve_path(settings.reports_dir))
    logger.info("Explainability reports written: %s", ", ".join(f.name for f in files))


if __name__ == "__main__":
    main()
